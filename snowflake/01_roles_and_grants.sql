-- 01_roles_and_grants.sql
-- Database, schemas and least-privilege roles: LOADER writes RAW,
-- TRANSFORMER (dbt) builds Bronze/Silver/Gold, ANALYST reads Gold only.

-- 1. Database and schemas
USE ROLE ACCOUNTADMIN;
CREATE DATABASE IF NOT EXISTS RENTALS_DB;
CREATE SCHEMA IF NOT EXISTS RENTALS_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS RENTALS_DB.RAW;
CREATE SCHEMA IF NOT EXISTS RENTALS_DB.BRONZE;
CREATE SCHEMA IF NOT EXISTS RENTALS_DB.SILVER;
CREATE SCHEMA IF NOT EXISTS RENTALS_DB.GOLD;

-- 2. Roles (SECURITYADMIN manages users, roles and grants)
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS LOADER      COMMENT = 'Loads files into RAW';
CREATE ROLE IF NOT EXISTS TRANSFORMER COMMENT = 'dbt: builds Bronze, Silver, Gold';
CREATE ROLE IF NOT EXISTS ANALYST     COMMENT = 'Read-only on Gold';

-- Roll custom roles up to SYSADMIN (Snowflake best practice)
GRANT ROLE LOADER      TO ROLE SYSADMIN;
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE ANALYST     TO ROLE SYSADMIN;

-- Give yourself all three so you can test each one
GRANT ROLE LOADER      TO USER RAMANDEEP;
GRANT ROLE TRANSFORMER TO USER RAMANDEEP;
GRANT ROLE ANALYST     TO USER RAMANDEEP;

-- 3. Warehouse and database access for all three
GRANT USAGE ON WAREHOUSE ELT_WH  TO ROLE LOADER;
GRANT USAGE ON WAREHOUSE ELT_WH  TO ROLE TRANSFORMER;
GRANT USAGE ON WAREHOUSE ELT_WH  TO ROLE ANALYST;
GRANT USAGE ON DATABASE RENTALS_DB TO ROLE LOADER;
GRANT USAGE ON DATABASE RENTALS_DB TO ROLE TRANSFORMER;
GRANT USAGE ON DATABASE RENTALS_DB TO ROLE ANALYST;

-- 4. LOADER owns RAW
GRANT OWNERSHIP ON SCHEMA RENTALS_DB.RAW TO ROLE LOADER COPY CURRENT GRANTS;

-- 5. TRANSFORMER reads RAW and STAGING
GRANT USAGE  ON SCHEMA RENTALS_DB.RAW                        TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RENTALS_DB.RAW       TO ROLE TRANSFORMER;
GRANT USAGE  ON SCHEMA RENTALS_DB.STAGING                    TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA RENTALS_DB.STAGING      TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RENTALS_DB.STAGING   TO ROLE TRANSFORMER;

-- 6. TRANSFORMER owns the dbt layers (dbt needs ownership to replace tables)
GRANT OWNERSHIP ON SCHEMA RENTALS_DB.BRONZE TO ROLE TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA RENTALS_DB.SILVER TO ROLE TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA RENTALS_DB.GOLD   TO ROLE TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL TABLES IN SCHEMA RENTALS_DB.BRONZE TO ROLE TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL TABLES IN SCHEMA RENTALS_DB.SILVER TO ROLE TRANSFORMER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL TABLES IN SCHEMA RENTALS_DB.GOLD   TO ROLE TRANSFORMER COPY CURRENT GRANTS;
GRANT CREATE SCHEMA ON DATABASE RENTALS_DB TO ROLE TRANSFORMER;  -- for the CI dev schema later

-- 7. ANALYST reads Gold only (current and future objects)
GRANT USAGE  ON SCHEMA RENTALS_DB.GOLD                          TO ROLE ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA RENTALS_DB.GOLD            TO ROLE ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RENTALS_DB.GOLD         TO ROLE ANALYST;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA RENTALS_DB.GOLD          TO ROLE ANALYST;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA RENTALS_DB.GOLD TO ROLE ANALYST;

-- 8. Turn off secondary roles so each role is tested on its own
USE ROLE ACCOUNTADMIN;
ALTER USER RAMANDEEP SET DEFAULT_SECONDARY_ROLES = ();

-- 9. Verify
SHOW GRANTS TO ROLE TRANSFORMER;
SHOW GRANTS TO ROLE ANALYST;